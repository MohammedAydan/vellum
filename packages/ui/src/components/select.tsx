/**
 * Derive a fallback accessible name from the `placeholder` of a child
 * `SelectValue`. Radix renders the trigger as a `<button>` whose only visible
 * content is the placeholder text, so without an explicit aria-label axe
 * reports a `button-name` violation. Call sites are unchanged: we introspect
 * the children instead of asking each one to pass an aria-label.
 */
function getSelectAccessibleName(children: React.ReactNode): string {
  let placeholder: string | undefined
  React.Children.forEach(children, (child) => {
    if (placeholder !== undefined || !React.isValidElement(child)) return
    if (child.type !== SelectValue && child.type !== SelectPrimitive.Value)
      return
    const value = (child.props as { placeholder?: unknown }).placeholder
    if (typeof value === "string" && value.length > 0) placeholder = value
  })
  return placeholder ?? "Select"
}

const SelectTrigger = React.forwardRef<
  React.ElementRef<typeof SelectPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Trigger> & {
    size?: "sm" | "default"
  }
>(
  (
    {
      className,
      size = "default",
      children,
      "aria-label": ariaLabel,
      "aria-labelledby": ariaLabelledBy,
      ...props
    },
    ref
  ) => {
    // Preserve any name the caller already provided. Only synthesize one when
    // neither aria-label nor aria-labelledby is present.
    const hasAccessibleName = ariaLabel != null || ariaLabelledBy != null
    const resolvedAriaLabel = hasAccessibleName
      ? ariaLabel
      : getSelectAccessibleName(children)

    return (
      <SelectPrimitive.Trigger
        ref={ref}
        data-slot="select-trigger"
        data-size={size}
        aria-label={resolvedAriaLabel}
        aria-labelledby={ariaLabelledBy}
        className={cn(
          "flex w-fit items-center justify-between gap-1.5 rounded-md border border-input bg-transparent py-2 pe-2 ps-2.5 text-sm whitespace-nowrap transition-colors outline-none select-none focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50 disabled:cursor-not-allowed disabled:opacity-50 aria-invalid:border-destructive aria-invalid:ring-3 aria-invalid:ring-destructive/20 data-placeholder:text-muted-foreground data-[size=default]:h-8 data-[size=sm]:h-7 data-[size=sm]:rounded-[min(var(--radius-md),10px)] *:data-[slot=select-value]:line-clamp-1 *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-1.5 dark:bg-input/30 dark:hover:bg-input/50 dark:aria-invalid:border-destructive/50 dark:aria-invalid:ring-destructive/40 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
          className
        )}
        {...props}
      >
        {children}
        <SelectPrimitive.Icon asChild>
          <ChevronDown className="pointer-events-none size-4 text-muted-foreground" />
        </SelectPrimitive.Icon>
      </SelectPrimitive.Trigger>
    )
  }
)
SelectTrigger.displayName = SelectPrimitive.Trigger.displayName

